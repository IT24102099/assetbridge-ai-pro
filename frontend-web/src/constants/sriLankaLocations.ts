export const SRI_LANKA_DISTRICTS = Object.keys(SRI_LANKA_LOCATION_DATA);

export function getCitiesForDistrict(district: string): string[] {
  if (!district) return [];
  const key = Object.keys(SRI_LANKA_LOCATION_DATA).find(
    (d) => d.toLowerCase() === district.trim().toLowerCase()
  );
  return key ? SRI_LANKA_LOCATION_DATA[key] : [];
}

export function isValidDistrictCityCombination(district: string, city: string): boolean {
  if (!district || !city) return false;
  const dTrim = district.trim().toLowerCase();
  const cTrim = city.trim().toLowerCase();

  const districtKey = Object.keys(SRI_LANKA_LOCATION_DATA).find(
    (d) => d.toLowerCase() === dTrim
  );
  if (!districtKey) return false;

  const validCities = SRI_LANKA_LOCATION_DATA[districtKey];
  if (validCities.some((c) => c.toLowerCase() === cTrim)) {
    return true;
  }

  // If city matches another district or one of that other district's known cities, reject
  for (const [otherDist, otherCities] of Object.entries(SRI_LANKA_LOCATION_DATA)) {
    if (otherDist.toLowerCase() !== districtKey.toLowerCase()) {
      if (
        otherDist.toLowerCase() === cTrim ||
        otherCities.some((c) => c.toLowerCase() === cTrim)
      ) {
        return false;
      }
    }
  }

  return true;
}
